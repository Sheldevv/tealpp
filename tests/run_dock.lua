local Dock = require("gamekit.dock")
local passed = 0
local function test(name, fn)
    local ok, err = pcall(fn)
    if not ok then print("FAIL: " .. name .. "\n  " .. tostring(err)); os.exit(1) end
    passed = passed + 1; print("PASS: " .. name)
end
local function near(a, b) assert(math.abs(a - b) < 0.0001, tostring(a) .. " ~= " .. tostring(b)) end

test("panels can be added and removed", function()
    local d = Dock.new({width = 800, height = 600})
    local p = d:add("scene", {title = "Scene", x = 30, y = 40, w = 200, h = 150})
    assert(d:get("scene") == p); assert(d:remove("scene")); assert(not d:get("scene"))
end)
test("edge docking fills the available height", function()
    local d = Dock.new({x = 10, y = 20, width = 800, height = 600})
    local p = d:add("inspector", {w = 220, dock = "left"})
    near(p.x, 10); near(p.y, 20); near(p.h, 600)
end)
test("collapse toggles panel content height", function()
    local d = Dock.new({width = 800, height = 600})
    local p = d:add("assets", {x = 20, y = 20, w = 300, h = 220})
    assert(d:toggleCollapsed(p)); assert(p.collapsed)
    assert(not d:toggleCollapsed(p)); assert(not p.collapsed)
end)
test("dragging a title bar moves floating panels", function()
    local d = Dock.new({width = 800, height = 600})
    local p = d:add("scene", {x = 100, y = 100, w = 200, h = 150})
    d:mousepressed(130, 110, 1); d:mousemoved(230, 210); d:mousereleased(230, 210, 1)
    near(p.x, 200); near(p.y, 200)
end)
test("resize grip respects minimum dimensions", function()
    local d = Dock.new({width = 800, height = 600})
    local p = d:add("scene", {x = 100, y = 100, w = 200, h = 150, min_w = 180, min_h = 100})
    d:mousepressed(295, 245, 1); d:mousemoved(80, 80); d:mousereleased(80, 80, 1)
    near(p.w, 180); near(p.h, 100)
end)
test("draw renders visible panels", function()
    local d = Dock.new({width = 800, height = 600})
    d:add("scene", {title = "Scene"})
    local rects, texts = 0, 0
    d:draw({rect = function() rects = rects + 1 end, text = function() texts = texts + 1 end})
    assert(rects >= 3); assert(texts >= 2)
end)
print(passed .. " dock tests passed!")
