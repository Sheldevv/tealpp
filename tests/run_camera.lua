local Camera = require("gamekit.camera")
local passed = 0
local function test(name, fn)
    local ok, err = pcall(fn)
    if not ok then print("FAIL: " .. name .. "\n  " .. tostring(err)); os.exit(1) end
    passed = passed + 1; print("PASS: " .. name)
end
local function near(a, b) assert(math.abs(a - b) < 0.0001, tostring(a) .. " ~= " .. tostring(b)) end

test("world and screen coordinates round-trip", function()
    local c = Camera.new({x = 40, y = -20, zoom = 2, width = 800, height = 600})
    local sx, sy = c:worldToScreen(150, 75)
    local wx, wy = c:screenToWorld(sx, sy)
    near(wx, 150); near(wy, 75)
end)
test("rotation round-trips coordinates", function()
    local c = Camera.new({x = 3, y = 9, zoom = 1.5, rotation = 0.7, width = 800, height = 600})
    local sx, sy = c:worldToScreen(-20, 55)
    local wx, wy = c:screenToWorld(sx, sy)
    near(wx, -20); near(wy, 55)
end)
test("zoom is clamped to configured limits", function()
    local c = Camera.new({min_zoom = 0.5, max_zoom = 3})
    c:setZoom(100); near(c.zoom, 3)
    c:setZoom(0.01); near(c.zoom, 0.5)
end)
test("zooming around a screen point preserves its world point", function()
    local c = Camera.new({x = 12, y = 20, zoom = 1, width = 640, height = 480})
    local wx, wy = c:screenToWorld(180, 210)
    c:zoomBy(2, 180, 210)
    local ax, ay = c:screenToWorld(180, 210)
    near(ax, wx); near(ay, wy)
end)
test("viewport containment and visible bounds", function()
    local c = Camera.new({viewport_x = 10, viewport_y = 20, width = 100, height = 50})
    assert(c:containsScreenPoint(10, 20)); assert(not c:containsScreenPoint(0, 0))
    local x, y, w, h = c:getVisibleWorldBounds()
    near(x, -50); near(y, -25); near(w, 100); near(h, 50)
end)
print(passed .. " camera tests passed!")
